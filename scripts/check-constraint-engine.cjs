'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const E=require('../labs/constraint-engine.js');
const H=(x,y)=>({type:'projection',plane:'H',value:[x,y]});
const V=(x,z)=>({type:'projection',plane:'V',value:[x,z]});
const P={type:'plane',normal:{x:-.3,y:-.4,z:1},offset:10};
const C=(axis,value)=>({type:'coordinate',axis,value});
const L={type:'line',point:{x:10,y:20,z:15},direction:{x:1,y:2,z:1}};
function check(cs,degrees,states){
 const a=E.analyze(cs);
 assert.equal(a.result.degrees,degrees);
 assert.deepEqual(a.steps.map(s=>s.status),states);
 return a;
}
check([],3,[]);
check([H(35,35)],1,['independent']);
let a=check([H(35,35),P],0,['independent','independent']);
assert(Math.abs(a.result.particular[2]-34.5)<1e-6,'plane intersection z should equal 34.5');
check([P],2,['independent']);
check([P,H(35,35)],0,['independent','independent']);
a=check([V(40,50),H(40,35)],0,['independent','independent']);
assert.deepEqual(a.result.particular.map(Math.round),[40,35,50]);
check([H(35,35),C('x',35)],1,['independent','redundant']);
check([H(35,35),C('x',40)],null,['independent','contradiction']);
a=check([L],1,['independent']);
a=check([L,C('z',35)],0,['independent','independent']);
assert.deepEqual(a.result.particular.map(Math.round),[30,60,35]);
check([L,C('z',35),C('x',50)],null,['independent','independent','contradiction']);
check([C('x',35),C('y',35),C('z',50)],0,['independent','independent','independent']);
assert.throws(()=>E.analyze([{type:'plane',normal:{x:0,y:0,z:0},offset:0}]));
assert.throws(()=>E.analyze([{type:'line',point:{x:0,y:0,z:0},direction:{x:0,y:0,z:0}}]));
const page=fs.readFileSync('labs/analysis.html','utf8');
assert(page.includes('constraint-engine.js'));
assert(page.includes('例题一')&&page.includes('例题二')&&page.includes('例题三'));
for(const id of ['examples','add','undo','reset','steps','status','summary','strategy','try'])assert(page.includes('id="'+id+'"'),id+' missing');
const scripts=[...page.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]).filter(Boolean);
assert.equal(scripts.length,1);
new vm.Script(scripts[0]);
console.log('PASS linear constraints: independent/redundant/conflicting; 3 representative examples; lab page syntax');
