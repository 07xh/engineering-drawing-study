'use strict';
const assert=require('node:assert/strict');
const G=require('../labs/dof-lab-geometry.js');
const S=require('../labs/dof-lab-sheet.js');
const model=G.preset('cuboid'),p={x:35,y:22,z:51};
const html=S.markup(model,p,{showLabels:true,selectedVertex:'A'});
assert.match(html,/正视图 V/);assert.match(html,/俯视图 H/);assert.match(html,/左视图 W/);
assert.match(html,/45°/);assert.match(html,/class="sheet-miter"/);
assert.match(html,/凸多面体的虚实线/);
assert.equal((html.match(/class="sheet-edge sheet-edge-(?:visible|hidden)"/g)||[]).length,24);
assert.equal((html.match(/data-kind="depth-HM"/g)||[]).length,1);
assert.equal((html.match(/data-kind="depth-MW"/g)||[]).length,1);
assert.equal((html.match(/data-target-view=/g)||[]).length,3);
assert(html.includes('data-vertex="A"'));
const hidden=S.markup(model,p,{showGuides:false,showWireframe:false});
assert(!hidden.includes('data-kind="depth-HM"'));
assert(!hidden.includes('class="sheet-edge sheet-edge-'));
assert(hidden.includes('class="sheet-miter"'),'45-degree reference must remain on same sheet');
assert.equal((hidden.match(/data-target-view=/g)||[]).length,3);
const absent=S.markup(model,p,{showTarget:false});
assert.equal((absent.match(/data-target-view=/g)||[]).length,0,'unsatisfiable model cannot display point projections');
assert(absent.includes('class="sheet-miter"'),'the sheet itself remains visible when P is impossible');
const trans=G.transfer(p);
assert(Object.values(trans.checks).every(Boolean));
const v=G.projectPoint({x:35,y:22,z:51}),shift=G.projectPoint({x:35,y:32,z:51});
assert.equal(v.V.x,shift.V.x);assert.equal(v.V.y,shift.V.y);
assert.equal(v.H.x,shift.H.x);assert.notEqual(v.H.y,shift.H.y);
assert.notEqual(v.W.x,shift.W.x);assert.equal(v.W.y,shift.W.y);
console.log('PASS: V/H/W share one first-angle drawing sheet, 45-degree transfer and synchronized point projections');
