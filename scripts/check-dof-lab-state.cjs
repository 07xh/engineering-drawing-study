'use strict';
const assert=require('node:assert/strict'),S=require('../labs/dof-lab-state.js');
let s=S.create(),r=S.compute(s);
assert.equal(r.analysis.result.degrees,3);
assert.equal(r.point.kind,'space');
assert.equal(s.conditions.length,0);
const H={type:'projection',plane:'H',value:[35,22]};
s=S.apply(s,{type:'add',condition:H});
assert.equal(S.compute(s).analysis.result.degrees,1);
assert.equal(s.conditions.length,1);
const old=s;
s=S.apply(s,{type:'add',condition:{type:'plane',normal:{x:0,y:0,z:1},offset:51}});
assert.equal(old.conditions.length,1,'state mutation must be immutable');
assert.equal(S.compute(s).analysis.result.degrees,0);
assert.deepEqual(S.compute(s).point.example,{x:35,y:22,z:51});
s=S.apply(s,{type:'toggle',index:1});
assert.equal(S.compute(s).analysis.result.degrees,1);
s=S.apply(s,{type:'edit',index:0,condition:{type:'projection',plane:'V',value:[35,51]}});
assert.equal(S.compute(s).analysis.result.degrees,1);
s=S.apply(s,{type:'toggle',index:1});
assert.equal(S.compute(s).analysis.result.degrees,1,'already known z-plane must be redundant with V projection');
assert.equal(S.compute(s).analysis.steps[1].status,'redundant');
s=S.apply(s,{type:'add',condition:{type:'coordinate',axis:'y',value:22}});
assert.equal(S.compute(s).analysis.result.degrees,0);
s=S.apply(s,{type:'add',condition:{type:'coordinate',axis:'x',value:50}});
assert.equal(S.compute(s).analysis.result.inconsistent,true);
assert.equal(S.compute(s).point.kind,'none');
s=S.apply(s,{type:'remove',index:3});
assert.equal(S.compute(s).analysis.result.inconsistent,false);
s=S.apply(s,{type:'clear'});
assert.equal(S.compute(s).analysis.result.degrees,3);
s=S.apply(s,{type:'set-model',value:'triangular-prism'});
assert.equal(S.compute(s).model.edges.length,9);
assert.throws(()=>S.apply(s,{type:'add',condition:{type:'sphere',radius:5}}),/仅支持/);
assert.throws(()=>S.apply(s,{type:'add',condition:{type:'line',point:{x:0,y:0,z:0},direction:{x:0,y:0,z:0}}}),/方向向量/);
assert.throws(()=>S.apply(s,{type:'edit',index:20,condition:H}),/未知约束行/);
console.log('PASS: empty start, full constraint CRUD, DOF recomputation, redundancy/contradiction and immutable state');
