'use strict';
const assert=require('node:assert/strict');
const N=require('../knowledge/nonlinear-local-dof.js');
const S=require('../knowledge/player-dof-summary.js');
const A=require('../knowledge/textbook-action-adapter.js');
const E=require('../knowledge/textbook-examples.js');
const G=require('../knowledge/textbook-example-geometry.js');
const steps=A.adapt(E.get('example-1-1'),G).steps;
const results=steps.map((step,i)=>S.summarize(step.localDofAnalysis,i?steps[i-1].localDofAnalysis:null));
assert.deepEqual(results.map(x=>x.currentDegrees),[1,1,1,0,0]);
assert.deepEqual(results.map(x=>x.removedDegrees),[null,0,0,1,0]);
assert.ok(results.every(x=>x.available));
assert.deepEqual(steps.map(x=>x.localDofAnalysis.constraints.length),[1,1,1,2,2]);
assert.equal(steps[0].localDofAnalysis.points.Q1.x,G.frame('example-1-1',0).proof.points[1].x);
assert.match(steps[3].localDofExplanation.reason,/相交/);
assert(steps.every(s=>s.localDofExplanation.scope.includes('仅计算归一化示意中的 Q1')));
assert(steps.every(s=>!s.constraintAnalysis),'do not invent a global uniqueness claim');
const model=steps[3].localDofAnalysis;
const invalid={points:{Q1:{x:model.points.Q1.x+13,y:model.points.Q1.y}},constraints:model.constraints};
assert.equal(N.analyze(invalid).atProvidedConfiguration,false);
assert.equal(S.summarize(invalid,steps[2].localDofAnalysis).available,false);
const offLine={points:{Q1:{x:25,y:19}},constraints:[{type:'on-line',point:'Q1',line:{a:0,b:10,offset:0}}]};
assert.equal(N.analyze(offLine).atProvidedConfiguration,false);
const scaled=N.analyze({points:{Q1:{x:3,y:4}},constraints:[{type:'on-line',point:'Q1',line:{a:5,b:0,offset:15}}]});
assert.equal(scaled.rank,1);
assert.equal(scaled.localDegrees,1);
assert.equal(scaled.atProvidedConfiguration,true);
assert.throws(()=>N.analyze({points:{Q1:{x:0,y:0}},constraints:[{type:'on-line',point:'Q1',line:{a:0,b:0,offset:0}}]}),/零法向量/);
assert.throws(()=>N.analyze({points:{Q1:{x:0,y:0}},constraints:[{type:'on-line',point:'Q1',line:{a:NaN,b:1,offset:0}}]}),/系数无效/);
console.log('PASS: reviewed Example 1-1 Q1 line-intersection constraints [1,1,1,0,0] and malformed-line guard');
