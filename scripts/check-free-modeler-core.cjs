'use strict';
const assert=require('node:assert/strict');
const G=require('../labs/dof-lab-geometry.js'),F=require('../labs/free-geometry-core.js'),Sheet=require('../labs/free-geometry-sheet.js');
let state=F.create();
assert.equal(F.summary(state).unconstrainedDegrees,0);
assert.equal(F.asModel(state).faces.length,0);
let drawing=Sheet.markup(state);
assert(drawing.includes('空白图纸'));
assert(drawing.includes('正视图 V')&&drawing.includes('俯视图 H')&&drawing.includes('左视图 W'));
assert(drawing.includes('45°'));
const orig=state;
state=F.apply(state,{type:'add-point',x:32,y:18,z:40});
assert.equal(orig.points.length,0,'add must not mutate previous state');
assert.equal(state.points[0].id,'A');
state=F.apply(state,{type:'add-point',id:'点乙',x:60,y:18,z:40});
assert.equal(F.summary(state).unconstrainedDegrees,6);
state=F.apply(state,{type:'add-edge',a:'A',b:'点乙'});
assert.equal(state.edges.length,1);
assert.equal(F.summary(state).unconstrainedDegrees,6,'a drawn line is not an implicit fixed-length constraint');
assert.equal(F.asModel(state).faces.length,0);
assert(G.validate(F.asModel(state)));
drawing=Sheet.markup(state,{selectedPoint:'A'});
assert.equal((drawing.match(/data-segment=/g)||[]).length,2,'constant-depth AB projects as nondegenerate V/H but W collapses');
assert.equal((drawing.match(/data-kind=/g)||[]).length,4);
assert.equal((drawing.match(/data-point=/g)||[]).length,6);
assert(drawing.includes('点乙'));
assert(drawing.includes('45°'));
const q=Sheet.project(state).points.A,o=G.ORIGIN;
assert.equal(q.V.x,q.H.x);
assert.equal(q.V.y,q.W.y);
assert(Math.abs(q.H.y-o.y-(q.W.x-o.x))<1e-8);
assert(Math.abs(q.M.x-o.x-(q.M.y-o.y))<1e-8);
assert.deepEqual(F.projected(state).A,G.projectPoint(state.points[0]));
const moved=F.apply(state,{type:'edit-point',id:'A',newId:'C',x:35,y:20,z:44});
assert.deepEqual(state.edges,[{a:'A',b:'点乙'}]);
assert.deepEqual(moved.edges,[{a:'C',b:'点乙'}]);
assert.deepEqual(F.asModel(moved).points.C,{x:35,y:20,z:44});
assert.throws(()=>F.apply(moved,{type:'add-edge',a:'点乙',b:'C'}),/重复/);
assert.throws(()=>F.apply(moved,{type:'add-edge',a:'C',b:'C'}),/不同/);
assert.throws(()=>F.apply(moved,{type:'add-edge',a:'C',b:'missing'}),/已有点/);
assert.throws(()=>F.apply(moved,{type:'add-point',id:'C',x:0,y:0,z:0}),/已存在/);
assert.throws(()=>F.apply(moved,{type:'add-point',id:'<script>',x:0,y:0,z:0}),/点名/);
assert.throws(()=>F.apply(moved,{type:'add-point',id:'D',x:Infinity,y:0,z:0}),/有限/);
assert.throws(()=>F.apply(moved,{type:'edit-point',id:'absent',x:0,y:0,z:0}),/不存在/);
const clearedEdge=F.apply(moved,{type:'remove-edge',a:'点乙',b:'C'});
assert.equal(clearedEdge.edges.length,0);
const removed=F.apply(moved,{type:'remove-point',id:'C'});
assert.deepEqual(removed.edges,[],'deleting a point cascades to its incident segments');
assert.equal(removed.points.length,1);
assert.equal(F.apply(removed,{type:'clear'}).points.length,0);
assert.equal((Sheet.markup(F.create()).match(/data-point=/g)||[]).length,0);
const far=F.apply(F.create(),{type:'add-point',id:'R',x:900,y:900,z:900});
const rendered=Sheet.project(far);
assert(rendered.scale<G.SCALE,'sheet reduces scale to fit large coordinate magnitudes');
for(const view of ['V','H','W'])assert(Number.isFinite(rendered.points.R[view].x));
assert(!Sheet.markup(state,{showGuides:false,selectedPoint:'A'}).includes('data-kind="depth-HM"'));
console.log('PASS: user-created free points and segments, nonrigid DOF, first-angle sheet, edit/delete and zero-start');
