'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const engine=require('../labs/constraint-engine.js');
const bridge=require('../question-strategies.js');
const content=fs.readFileSync('content.js','utf8');
const context={window:{}};
vm.runInNewContext(content,context);
const questions=context.window.DRAWING_CONTENT.questions;
const expected=['Q009','Q010','Q011','Q012','Q013','Q014','Q015'];
for(const id of expected){
 const q=questions.find(x=>x.id===id);
 assert(q,'missing source question '+id);
 const result=bridge.analyzeQuestion(q,engine);
 assert(result&&result.analysis.steps.length>0,'missing computed analysis '+id);
 assert(!result.analysis.result.inconsistent,'curated question must be solvable '+id);
 assert.equal(result.analysis.result.degrees,0,'complete example must locate point '+id);
 assert(result.paper&&result.focus,'missing strategy '+id);
}
const redundant=bridge.analyzeQuestion({id:'Q013'},engine);
assert.equal(redundant.analysis.steps[1].result.rank,3,'two projections must fix three coordinates');
assert.equal(redundant.analysis.steps[1].addedEquations,2,'second projection has two coordinate equations');
assert.equal(bridge.forQuestion({id:'Q001'}),null,'unrelated theory must not get fabricated freedom count');
assert.equal(bridge.forQuestion(null),null);
const html=fs.readFileSync('index.html','utf8');
const app=fs.readFileSync('app.js','utf8');
const build=fs.readFileSync('scripts/build-static.cjs','utf8');
assert(html.indexOf('labs/constraint-engine.js')<html.indexOf('question-strategies.js'));
assert(html.indexOf('question-strategies.js')<html.indexOf('src="app.js"'));
for(const id of ['questionStrategy','strategyToggle','strategyDetail'])assert(html.includes('id="'+id+'"'));
assert(app.includes('renderQuestionStrategy(q)'),'strategy must follow quiz navigation');
assert(build.includes("'question-strategies.js'"),'new asset must be deployed');
new vm.Script(app);
console.log('PASS 7 curated questions, shared engine bridge, quiz navigation and deployment assets');
