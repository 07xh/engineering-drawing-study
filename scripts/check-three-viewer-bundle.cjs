'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),html=fs.readFileSync(path.join(root,'labs/dof-lab-v2.html'),'utf8');
const ui=fs.readFileSync(path.join(root,'labs/dof-lab-v2-ui.js'),'utf8');
const entry=fs.readFileSync(path.join(root,'labs/dof-lab-three-entry.js'),'utf8');
const bundlePath=path.join(root,'dist/labs/dof-lab-three-bundle.js');
assert(html.includes('id="threeSpace"'), 'WebGL viewport must have a container');
assert(html.includes('id="space"'), 'SVG fallback must stay present');
assert(html.includes('src="dof-lab-three-bundle.js"'), 'use build-local Three.js, not CDN');
assert(html.indexOf('dof-lab-geometry.js')<html.indexOf('dof-lab-three-bundle.js'));
assert(html.indexOf('dof-lab-three-bundle.js')<html.indexOf('dof-lab-v2-ui.js'));
assert(ui.includes('window.DrawingLabThreeViewer?.mount'));
assert(ui.includes("$('space').hidden=true"),'SVG should be hidden only after WebGL mounts');
assert(ui.includes('else $(\'space\').innerHTML=Spatial.markup'),'fallback must remain wired');
assert(entry.includes("import * as THREE from 'three'"));
assert(entry.includes("from 'three/addons/controls/OrbitControls.js'"));
assert(entry.includes('webgl2'));
assert(entry.includes('raycaster.intersectObjects'));
assert(entry.includes('dispose()'),'renderer should support cleanup');
assert(fs.existsSync(bundlePath),'Three.js bundle must be generated by static build');
const bytes=fs.statSync(bundlePath).size;
assert(bytes>100000&&bytes<2500000,'unexpected WebGL bundle size: '+bytes);
const packed=fs.readFileSync(bundlePath,'utf8');
assert(packed.includes('DrawingLabThreeViewer'),'global viewer bridge missing from bundle');
assert(!html.includes('https://cdn.')&&!html.includes('https://esm.sh'),'no runtime third-party CDN');
console.log('PASS: bundled WebGL 3D viewer ('+bytes+' bytes), SVG fallback, no runtime CDN, and working static references');
