'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {parseHTML}=require('linkedom');
const {homeHTML}=require('../../ui-next/home.cjs');
const {prismMesh}=require('../../project/unified-workbench-session.cjs');
const {project}=require('../../core/projection/conventions.js');
const {IDS}=require('../../project/c1-reviewed-input.cjs');
const tick=()=>new Promise(resolve=>setImmediate(resolve));
test('C1 is a REAL reviewed task within same local project and original V5 player',async()=>{
 const {document,window}=parseHTML('<html><body>'+homeHTML()+'</body></html>');
 const create=document.createElement.bind(document);
 function adapt(el){
  if(!el||el.nodeType!==1)return el;
  for(const name of ['disabled','hidden','checked'])Object.defineProperty(el,name,{
   configurable:true,get(){return this.hasAttribute(name)},
   set(value){value?this.setAttribute(name,''):this.removeAttribute(name)}
  });
  if(['INPUT','SELECT','OPTION','TEXTAREA'].includes(el.tagName))
   Object.defineProperty(el,'value',{configurable:true,
    get(){
     if(Object.hasOwn(this,'__c1Value'))return this.__c1Value;
     if(this.tagName==='SELECT')return (this.querySelector('option[selected]')||
       this.querySelector('option'))?.value||'';
     return this.getAttribute('value')??'';
    },set(v){this.__c1Value=String(v)}
   });
  return el;
 }
 for(const el of document.querySelectorAll('*'))adapt(el);
 Object.defineProperty(document,'createElement',{configurable:true,value:t=>adapt(create(t))});
 const prev={document:global.document,window:global.window};
 global.document=document;global.window=window;
 global.requestAnimationFrame=cb=>setImmediate(()=>cb(performance.now()));
 global.cancelAnimationFrame=clearImmediate;
 const $=id=>document.getElementById(id);
 const fire=(id,event)=>$(id).dispatchEvent(new window.Event(event,{bubbles:true}));
 try{
  assert.ok(document.querySelector('fieldset[data-v7-task="c1-third-view"]'));
  assert.equal($('v8-c1-vertices').value,'','unfamiliar problem cannot silently inherit demo coordinates');
  require('../../project/unified-workbench-entry.cjs');
  for(let i=0;i<12&&!$('v7-review').textContent.includes('尚未提交');i++)await tick();
  $('v7-task').value='c1-third-view';fire('v7-task','change');
  for(let i=0;i<6;i++)await tick();
  assert.equal(document.querySelector('fieldset[data-v7-task="c1-third-view"]').hidden,false);
  const template=prismMesh({solid:{min:{x:0,y:0,z:0},max:{x:30,y:15,z:20}}});
  const rows=IDS.map(id=>{
    const views=project(template.data.points[id]);
    return [id,views.V.u,views.V.v,views.H.u,views.H.v].join(',');
  }).join('\n');
  $('v8-c1-vertices').value=rows;fire('v8-c1-vertices','input');
  // A checkbox is a human declaration, not generated by the input bridge.
  assert.equal($('v8-c1-topology').checked,false);
  $('v8-c1-topology').checked=true;fire('v8-c1-topology','change');
  $('v8-review-ack').checked=true;fire('v8-review-ack','change');
  assert.equal($('v8-review-run').disabled,false);
  fire('v8-review-run','click');
  for(let i=0;i<16;i++)await tick();
  assert.match($('v7-proof').textContent,/C1 八角点两已知视图复算/,$('v7-save').textContent);
  assert.match($('v8-result-status').textContent,/局部数学预览/);
  assert.equal($('v8-result-status').dataset.state,'partial');
  assert.equal($('v7-play').disabled,false,'canonical V5 proof steps can play');
  assert.ok($('v7-step-list').querySelector('button'));
  assert.ok($('v7-sheet').querySelector('[data-geometry-id="C1Solid"]'));
  assert.equal($('v8-review-ack').checked,false);
  $('v8-c1-vertices').value=rows.replace('V000,0,0,0,0','V000,0,0,2,0');
  fire('v8-c1-vertices','input');
  await tick();await tick();
  assert.match($('v7-proof').textContent,/未计算/);
  assert.equal($('v7-play').disabled,true);
  assert.equal($('v8-review-run').disabled,true);
 }finally{
  global.document=prev.document;global.window=prev.window;
  delete global.requestAnimationFrame;delete global.cancelAnimationFrame;
 }
});
